// ---------------------------------------------------------------------------
// Explanation: real tree traversal → decisionPath
// ---------------------------------------------------------------------------

interface DecisionStep {
  step: string;
  condition: string;
  outcome: string;
}

function explainTraversal(x: number[], lang: Lang): DecisionStep[] {
  const s = STRINGS[lang];
  const labels = FEATURE_LABELS[lang];
  const tree = forest.trees[forest.primaryTreeIdx];
  const path: DecisionStep[] = [];
  let node = tree;
  let stepNum = 1;

  while (node.type === 'split') {
    const fName = FEATURE_NAMES[node.featureIdx];
    const label = labels[fName];
    const isBool = BOOL_FEATURES.has(fName);
    const goLeft = x[node.featureIdx] <= node.threshold;

    let condition: string;
    if (isBool) {
      condition = `${label} ${goLeft ? s.falseFlag : s.trueFlag}`;
    } else {
      condition = `${label} ${goLeft ? s.lte : s.gt} ${Math.round(node.threshold * 100) / 100}`;
    }

    path.push({
      step: `${s.nodeStep} ${stepNum}`,
      condition,
      outcome: goLeft ? s.movedLeft : s.movedRight,
    });

    node = goLeft ? node.left : node.right;
    stepNum++;
    if (stepNum > 12) break; // safety cap
  }

  if (node.type === 'leaf') {
    path.push({
      step: s.leafStep,
      condition: `n=${node.n}`,
      outcome: `${s.leafOutcome} ${Math.round(node.prob * 100)}%`,
    });
  }

  return path;
}

// ---------------------------------------------------------------------------
// Recommendations via counterfactual sensitivity analysis against the
// trained forest — perturb one feature toward a healthier value, re-run
// the actual model, and measure the real change in predicted probability.
// ---------------------------------------------------------------------------

function recommend(x: number[], baseProb: number, lang: Lang): string[] {
  const s = STRINGS[lang];
  const labels = FEATURE_LABELS[lang];

  const perturbations: { feature: FeatureName; apply: (v: number[]) => number[] }[] = [
    { feature: 'satisfaction', apply: (v) => { const c = [...v]; c[2] = Math.min(10, c[2] + 3); return c; } },
    { feature: 'jobInvolvement', apply: (v) => { const c = [...v]; c[5] = Math.min(4, c[5] + 1); return c; } },
    { feature: 'overTime', apply: (v) => { const c = [...v]; c[4] = 0; return c; } },
    { feature: 'commute', apply: (v) => { const c = [...v]; c[1] = Math.max(1, c[1] - 10); return c; } },
    { feature: 'emailSentimentRisk', apply: (v) => { const c = [...v]; c[8] = 0; return c; } },
    { feature: 'emailAfterHours', apply: (v) => { const c = [...v]; c[6] = 0; return c; } },
    { feature: 'emailResponseDelay', apply: (v) => { const c = [...v]; c[9] = 0; return c; } },
  ];

  const scored = perturbations
    .map((p) => {
      const newProb = forest.predictProba(p.apply(x));
      const delta = baseProb - newProb;
      return { feature: p.feature, delta };
    })
    .filter((r) => r.delta > 0.005)
    .sort((a, b) => b.delta - a.delta)
    .slice(0, 4);

  if (scored.length === 0) {
    return [s.recNone];
  }

  return scored.map(
    (r) =>
      `${s.recImprove} ${labels[r.feature]} ${s.recWouldLower} ${Math.round(r.delta * 100)}%.`
  );
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

export interface AnalysisResult {
  riskLevel: 'Low' | 'Medium' | 'High';
  riskScore: number;
  decisionPath: DecisionStep[];
  recommendations: string[];
}

export function analyzeAttrition(input: EmployeeFeatures, lang: string): AnalysisResult {
  const validLang: Lang = (['en', 'es', 'de', 'fr', 'tr', 'zh'] as const).includes(lang as Lang)
    ? (lang as Lang)
    : 'en';

  const x = toVector(input);
  const prob = forest.predictProba(x);
  const riskScore = Math.round(prob * 100);
  const riskLevel: 'Low' | 'Medium' | 'High' = riskScore >= 66 ? 'High' : riskScore >= 33 ? 'Medium' : 'Low';

  return {
    riskLevel,
    riskScore,
    decisionPath: explainTraversal(x, validLang),
    recommendations: recommend(x, prob, validLang),
  };
}

